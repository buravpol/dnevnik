export const АЛЬФА_EMA = 0.2; // как в таблице и в приложении ТФА

/** Сглаженный вес: 20% сегодняшнего + 80% истории. Возвращает [{date, вес, сглаженный}]. */
export function сглаженныйВес(точки, альфа = АЛЬФА_EMA) {
  const чистые = точки
    .filter((т) => Number.isFinite(т.вес) && т.вес > 0 && т.вес < 500)
    .sort((а, б) => (а.date < б.date ? -1 : 1));
  let ема = null;
  return чистые.map((т) => {
    ема = ема === null ? т.вес : альфа * т.вес + (1 - альфа) * ема;
    return { date: т.date, вес: т.вес, сглаженный: Math.round(ема * 10) / 10 };
  });
}

/** Недельный отвес в процентах: среднее за 7 дней против предыдущих 7. */
export function недельныйОтвес(точки) {
  const ряд = точки
    .filter((т) => Number.isFinite(т.вес) && т.вес > 0)
    .sort((а, б) => (а.date < б.date ? -1 : 1));
  if (ряд.length < 2) return { статус: 'нет-данных' };
  const конец = новаяДата(ряд[ряд.length - 1].date);
  const охват = (конец - новаяДата(ряд[0].date)) / 86400000;
  if (охват < 14) return { статус: 'рано' };
  const окно = (сдвиг) => {
    const до = сдвинуть(конец, -сдвиг * 7);
    const от = сдвинуть(до, -7);
    return ряд.filter((т) => новаяДата(т.date) > от && новаяДата(т.date) <= до);
  };
  const это = окно(0);
  const прошлое = окно(1);
  if (это.length < 4 || прошлое.length < 4) return { статус: 'мало-замеров' };
  const среднее = (м) => м.reduce((с, т) => с + т.вес, 0) / м.length;
  const был = среднее(прошлое);
  if (!был) return { статус: 'мало-замеров' };
  return { статус: 'ок', процент: ((среднее(это) - был) / был) * 100, стало: среднее(это), было: был };
}

/** Оценка одноповторного максимума — та же формула, что в приложении ТФА. */
export function одноповторный(вес, повторы, взапасе = 0) {
  if (!вес || !повторы) return null;
  return вес * (1 + 0.025 * (повторы + взапасе));
}

/** Тоннаж подхода/тренировки. */
export function тоннаж(подходы) {
  return подходы.reduce((сумма, п) => sum(сумма, п), 0);
  function sum(с, п) {
    if (!п || !п.вес || !п.повторы) return с;
    return с + п.вес * п.повторы;
  }
}

/** Калории из БЖУ, если не введены напрямую. */
export function калорииИзБЖУ({ белки = 0, жиры = 0, углеводы = 0 }) {
  return Math.round(белки * 4 + жиры * 9 + углеводы * 4);
}

/**
 * Расход калорий за день по факту: съедено + изменение запасов.
 * Опирается на сглаженный вес, поэтому считается только когда есть хотя бы два дня подряд.
 */
export function расход(съедено, весВчера, весСегодня) {
  if (!Number.isFinite(съедено) || !Number.isFinite(весВчера) || !Number.isFinite(весСегодня)) return null;
  const дельтаКг = весВчера - весСегодня;
  return съедено + дельтаКг * 7700;
}

/** Сколько граммов жира сожжено при дефиците. */
export function граммыЖира(дефицит) {
  if (!Number.isFinite(дефицит) || дефицит <= 0) return 0;
  return дефицит / 7.7;
}

/** Прогресс к цели по жиру: сколько уже потеряно из плана. */
export function прогрессПоЖиру(настройки, потеряноГрамм) {
  const план = настройки?.fatToLoseGrams;
  if (!план) return null;
  return { потеряно: Math.round(потеряноГрамм), план: Math.round(план),
           процент: Math.min(100, (потеряноГрамм / план) * 100) };
}

/** Частота рефида по проценту жира (женские пороги из таблицы). */
export function частотаРефида(процентЖира) {
  if (!Number.isFinite(процентЖира)) return null;
  if (процентЖира > 28) return 'рефид не обязателен';
  if (процентЖира > 23) return 'раз в две недели';
  if (процентЖира > 18) return 'раз в неделю';
  return 'один-два раза в неделю';
}

// ——— даты ———
export function сегодня() {
  return новаяДата(new Date()).toISOString().slice(0, 10);
}
export function новаяДата(значение) {
  const д = значение instanceof Date ? new Date(значение) : new Date(значение + 'T00:00:00');
  д.setHours(0, 0, 0, 0);
  return д;
}
export function сдвинуть(дата, дней) {
  const д = новаяДата(дата);
  д.setDate(д.getDate() + дней);
  return д;
}
export function ключДаты(дата) {
  return новаяДата(дата).toISOString().slice(0, 10);
}
export function поРусски(дата) {
  return новаяДата(дата).toLocaleDateString('ru-RU', { day: 'numeric', month: 'long' });
}

/** Среднее по числовому полю за последние N дней. */
export function среднееЗа(дни, поле, сколькоДней) {
  const порог = сдвинуть(сегодня(), -сколькоДней);
  const значения = дни
    .filter((д) => новаяДата(д.date) > порог && Number.isFinite(д[поле]))
    .map((д) => д[поле]);
  if (!значения.length) return null;
  return значения.reduce((с, з) => с + з, 0) / значения.length;
}

import { хранилище, день, сохранитьДень, настройки } from '../хранилище.js';
import { сегодня, калорииИзБЖУ } from '../расчёты.js';
import { нарисовать, приКлике, приВводе, число, отклик, обновить } from '../приложение.js';

const ПРИЁМЫ = ['Завтрак', 'Обед', 'Перекус', 'Ужин'];
let поиск = '';
let кудаДобавить = null;

function итого(позиции) {
  return позиции.reduce(
    (с, п) => ({
      ккал: с.ккал + (п.ккал || 0),
      белки: с.белки + (п.белки || 0),
      жиры: с.жиры + (п.жиры || 0),
      углеводы: с.углеводы + (п.углеводы || 0),
      клетчатка: с.клетчатка + (п.клетчатка || 0),
    }),
    { ккал: 0, белки: 0, жиры: 0, углеводы: 0, клетчатка: 0 }
  );
}

function посчитать(продукт, граммы) {
  const к = граммы / 100;
  return {
    продукт: продукт.name,
    граммы,
    ккал: Math.round((продукт.kcal || 0) * к),
    белки: Math.round((продукт.protein || 0) * к * 10) / 10,
    жиры: Math.round((продукт.fat || 0) * к * 10) / 10,
    углеводы: Math.round((продукт.carbs || 0) * к * 10) / 10,
    клетчатка: Math.round((продукт.fiber || 0) * к * 10) / 10,
  };
}

export async function показать() {
  const дата = сегодня();
  const запись = await день(дата);
  const н = await настройки();
  const рацион = запись.рацион || [];
  const сумма = итого(рацион);

  const планКкал = н.planKcal || н.kcalGoal || 1600;
  const планБелок = н.planProtein || н.proteinGoal || 140;

  if (кудаДобавить) return показатьВыбор();

  нарисовать(`
    <h1>Еда</h1>
    <p class="подпись">Планка на день — ${число(планКкал)} ккал, ${число(планБелок)} г белка</p>

    <div class="карточка лайм">
      <div class="строка">
        <div><div class="мелко">Съедено</div><div class="цифра">${число(сумма.ккал)}<small>ккал</small></div></div>
        <div style="text-align:right"><div class="мелко">Осталось</div>
          <div class="цифра">${число(планКкал - сумма.ккал)}</div></div>
      </div>
      <div class="полоса"><i class="${сумма.ккал > планКкал ? 'перебор' : ''}"
        style="width:${Math.min(100, (сумма.ккал / планКкал) * 100)}%"></i></div>
    </div>

    <div class="плитки">
      <div class="плитка"><div class="имя">Белки</div><div class="цифра">${число(сумма.белки)}<small>из ${число(планБелок)}</small></div></div>
      <div class="плитка"><div class="имя">Жиры</div><div class="цифра">${число(сумма.жиры)}<small>г</small></div></div>
      <div class="плитка"><div class="имя">Углеводы</div><div class="цифра">${число(сумма.углеводы)}<small>г</small></div></div>
      <div class="плитка"><div class="имя">Клетчатка</div><div class="цифра">${число(сумма.клетчатка)}<small>г</small></div></div>
    </div>

    ${ПРИЁМЫ.map((приём) => {
      const позиции = рацион.filter((п) => п.приём === приём);
      const и = итого(позиции);
      return `<h2>${приём}${позиции.length ? ` · ${число(и.ккал)} ккал` : ''}</h2>
        ${позиции
          .map(
            (п, i) => `<div class="карточка строка">
              <div>
                <div>${п.продукт}</div>
                <div class="мелко">${число(п.граммы)} г · ${число(п.ккал)} ккал · Б ${число(п.белки, 1)}</div>
              </div>
              <button class="кнопка тихая мелкая" data-убрать="${рацион.indexOf(п)}"
                style="width:46px;padding:13px 0">×</button>
            </div>`
          )
          .join('')}
        <button class="кнопка тихая" data-добавить="${приём}">Добавить</button>`;
    }).join('')}
  `);

  приКлике('[data-добавить]', (кнопка) => {
    кудаДобавить = кнопка.dataset.добавить;
    поиск = '';
    отклик();
    обновить();
  });

  приКлике('[data-убрать]', async (кнопка) => {
    const новый = безПозиции(рацион, Number(кнопка.dataset.убрать));
    await сохранитьДень(дата, { рацион: новый, ...пересчёт(новый) });
    отклик();
    обновить();
  });

}

function безПозиции(рацион, индекс) {
  return рацион.filter((_, i) => i !== индекс);
}

function пересчёт(рацион) {
  const с = итого(рацион);
  return {
    kcal: Math.round(с.ккал) || null,
    protein: Math.round(с.белки) || null,
    fat: Math.round(с.жиры) || null,
    carbs: Math.round(с.углеводы) || null,
    fiber: Math.round(с.клетчатка) || null,
  };
}

async function показатьВыбор() {
  const продукты = await хранилище.всё('продукты');
  const запрос = поиск.trim().toLowerCase();
  const найденные = (запрос
    ? продукты.filter((п) => п.name.toLowerCase().includes(запрос))
    : продукты
  ).slice(0, 60);

  нарисовать(`
    <div class="строка">
      <div><h1>${кудаДобавить}</h1><p class="подпись">${продукты.length} продуктов в базе</p></div>
      <button class="кнопка тихая мелкая" data-назад style="width:92px">Назад</button>
    </div>

    <div class="карточка">
      <input type="text" data-поиск placeholder="Найти продукт" value="${поиск}">
    </div>

    ${найденные
      .map(
        (п, i) => `<div class="карточка" data-продукт="${продукты.indexOf(п)}">
          <div class="строка">
            <div>
              <div>${п.name}</div>
              <div class="мелко">${п.group || ''} · ${число(п.kcal)} ккал / 100 г · Б ${число(п.protein, 1)}</div>
            </div>
            <div style="width:88px">
              <input type="number" inputmode="numeric" step="10" placeholder="г" data-граммы="${продукты.indexOf(п)}">
            </div>
          </div>
          <button class="кнопка" data-взять="${продукты.indexOf(п)}">Добавить</button>
        </div>`
      )
      .join('') || '<div class="пусто">Ничего не нашлось</div>'}
  `);

  приВводе('[data-поиск]', (поле) => {
    поиск = поле.value;
    обновить();
  }, 300);

  приКлике('[data-назад]', () => {
    кудаДобавить = null;
    обновить();
  });

  приКлике('[data-взять]', async (кнопка) => {
    const индекс = Number(кнопка.dataset.взять);
    const продукт = продукты[индекс];
    const поле = document.querySelector(`input[data-граммы="${индекс}"]`);
    const граммы = Number((поле?.value || '').replace(',', '.'));
    if (!Number.isFinite(граммы) || граммы <= 0) return отклик('rigid');

    const дата = сегодня();
    const запись = await день(дата);
    const рацион = [...(запись.рацион || []), { приём: кудаДобавить, ...посчитать(продукт, граммы) }];
    await сохранитьДень(дата, { рацион, ...пересчёт(рацион) });
    кудаДобавить = null;
    отклик('medium');
    обновить();
  });
}

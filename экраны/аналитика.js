import { хранилище, дни, настройки } from '../хранилище.js';
import { сглаженныйВес, недельныйОтвес, новаяДата, сдвинуть, сегодня, одноповторный } from '../расчёты.js';
import { линия, столбики, карточка } from '../графики.js';
import { нарисовать, приКлике, число, отклик, обновить } from '../приложение.js';

const ПЕРИОДЫ = [
  { дней: 30, имя: '30 дней' },
  { дней: 90, имя: '3 месяца' },
  { дней: 365, имя: 'год' },
  { дней: 3650, имя: 'всё' },
];
let период = 90;
let упражнение = null;

function заПериод(записи, дней, поле = 'date') {
  const порог = сдвинуть(сегодня(), -дней);
  return записи.filter((з) => новаяДата(з[поле]) > порог);
}

function подписиДат(записи) {
  if (записи.length < 2) return [];
  const первая = записи[0].date;
  const последняя = записи[записи.length - 1].date;
  const коротко = (д) => новаяДата(д).toLocaleDateString('ru-RU', { day: 'numeric', month: 'short' });
  return [коротко(первая), коротко(записи[Math.floor(записи.length / 2)].date), коротко(последняя)];
}

export async function показать() {
  const н = await настройки();
  const все = await дни();
  const тренировки = (await хранилище.всё('тренировки')).sort((а, б) => (а.дата < б.дата ? -1 : 1));
  const программы = await хранилище.всё('программы');

  const окно = заПериод(все, период);
  const ряд = сглаженныйВес(окно.map((д) => ({ date: д.date, вес: д.weight })));
  const отвес = недельныйОтвес(все.map((д) => ({ date: д.date, вес: д.weight })));

  const планКкал = н.planKcal || н.kcalGoal || 1600;
  const скалориями = окно.filter((д) => Number.isFinite(д.kcal));
  const сошагами = окно.filter((д) => Number.isFinite(д.steps));
  const сосном = окно.filter((д) => Number.isFinite(д.sleep));
  const сбелком = окно.filter((д) => Number.isFinite(д.protein));

  // прогресс по упражнениям: свои тренировки плюс перенесённая история
  const имена = new Set();
  for (const п of программы) for (const у of п.exercises || []) имена.add(у.name);
  for (const т of тренировки) for (const у of т.упражнения) имена.add(у.имя);
  const список = [...имена];
  const выбранное = упражнение && имена.has(упражнение) ? упражнение : список[0];

  нарисовать(`
    <h1>Графики</h1>
    <div class="пилюли">
      ${ПЕРИОДЫ.map(
        (п) => `<button data-период="${п.дней}" ${период === п.дней ? 'data-активно' : ''}>${п.имя}</button>`
      ).join('')}
    </div>

    ${карточка(
      'Вес',
      ряд.length
        ? число(ряд[ряд.length - 1].сглаженный, 1) + ' кг'
          + (отвес.статус === 'ок' ? ` · ${отвес.процент > 0 ? '+' : ''}${число(отвес.процент, 2)}% за неделю` : '')
        : '',
      линия(
        [
          { значения: ряд.map((т) => т.вес), цвет: 'var(--текст2)', толщина: 1.2, прозрачность: 0.55 },
          { значения: ряд.map((т) => т.сглаженный), цвет: 'var(--лайм)', толщина: 2.4 },
        ],
        подписиДат(ряд)
      )
    )}

    ${карточка(
      'Калории',
      скалориями.length ? 'в среднем ' + число(скалориями.reduce((с, д) => с + д.kcal, 0) / скалориями.length) : '',
      столбики(скалориями.map((д) => д.kcal), { цель: планКкал, подписи: подписиДат(скалориями) })
    )}

    ${карточка(
      'Белок',
      сбелком.length ? 'в среднем ' + число(сбелком.reduce((с, д) => с + д.protein, 0) / сбелком.length) + ' г' : '',
      столбики(сбелком.map((д) => д.protein), { подписи: подписиДат(сбелком), цвет: 'var(--белый)' })
    )}

    ${карточка(
      'Шаги',
      сошагами.length ? 'в среднем ' + число(сошагами.reduce((с, д) => с + д.steps, 0) / сошагами.length) : '',
      столбики(сошагами.map((д) => д.steps), { подписи: подписиДат(сошагами) })
    )}

    ${карточка(
      'Сон',
      сосном.length ? 'в среднем ' + число(сосном.reduce((с, д) => с + д.sleep, 0) / сосном.length, 1) + ' ч' : '',
      столбики(сосном.map((д) => д.sleep), { подписи: подписиДат(сосном), цвет: 'var(--белый)' })
    )}

    ${тренировки.length ? карточка(
      'Тоннаж тренировок',
      число(тренировки[тренировки.length - 1].тоннаж) + ' кг в последней',
      столбики(заПериод(тренировки, период, 'дата').map((т) => т.тоннаж), {})
    ) : ''}

    <h2>Прогресс по упражнению</h2>
    <div class="карточка">
      <select data-упражнение>
        ${список.map((и) => `<option ${и === выбранное ? 'selected' : ''}>${и}</option>`).join('')}
      </select>
    </div>
    ${графикУпражнения(выбранное, тренировки, программы)}

    <h2>Регулярность</h2>
    <div class="плитки">
      <div class="плитка"><div class="имя">Силовых за 30 дней</div>
        <div class="цифра">${заПериод(все, 30).filter((д) => д.strength).length}</div></div>
      <div class="плитка"><div class="имя">Дней с записями</div>
        <div class="цифра">${заПериод(все, 30).filter((д) => Number.isFinite(д.kcal) || Number.isFinite(д.weight)).length}</div></div>
    </div>
  `);

  приКлике('[data-период]', (кнопка) => {
    период = Number(кнопка.dataset.период);
    отклик();
    обновить();
  });

  document.querySelector('[data-упражнение]')?.addEventListener('change', (е) => {
    упражнение = е.target.value;
    обновить();
  });
}

function графикУпражнения(имя, тренировки, программы) {
  if (!имя) return '<div class="пусто">Пока нет упражнений</div>';
  const точки = [];

  for (const п of программы) {
    const у = (п.exercises || []).find((у) => у.name === имя);
    for (const н of у?.history || []) {
      const подходы = н.sets
        ? н.sets.flatMap((с) => (с.reps || []).map((п) => ({ вес: с.weight, повторы: п })))
        : (н.reps || []).map((п) => ({ вес: н.weight, повторы: п }));
      const лучший = подходы.reduce((м, п) => Math.max(м, одноповторный(п.вес, п.повторы) || 0), 0);
      const тоннаж = подходы.reduce((с, п) => с + (п.вес || 0) * (п.повторы || 0), 0);
      if (лучший) точки.push({ метка: 'н' + н.week, сила: лучший, тоннаж });
    }
  }

  for (const т of тренировки) {
    for (const у of т.упражнения.filter((у) => у.имя === имя)) {
      const лучший = у.подходы.reduce(
        (м, п) => Math.max(м, одноповторный(п.вес, п.повторы, п.взапасе) || 0), 0);
      const тоннаж = у.подходы.reduce((с, п) => с + (п.вес || 0) * (п.повторы || 0), 0);
      if (лучший) точки.push({ метка: т.дата.slice(5), сила: лучший, тоннаж });
    }
  }

  if (точки.length < 2) return '<div class="пусто">Нужно хотя бы две записи</div>';
  const последняя = точки[точки.length - 1];
  const первая = точки[0];
  const рост = ((последняя.сила - первая.сила) / первая.сила) * 100;

  return карточка(
    имя,
    `${число(последняя.сила, 1)} кг · ${рост > 0 ? '+' : ''}${число(рост, 1)}%`,
    линия([{ значения: точки.map((т) => т.сила), цвет: 'var(--лайм)', толщина: 2.4 }],
      [точки[0].метка, точки[Math.floor(точки.length / 2)].метка, последняя.метка])
  ) + карточка('Тоннаж упражнения', '',
    столбики(точки.map((т) => т.тоннаж), { цвет: 'var(--белый)' }));
}

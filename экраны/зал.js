import { хранилище, вОчередь, сохранитьДень } from '../хранилище.js';
import { сегодня, поРусски, одноповторный } from '../расчёты.js';
import { нарисовать, приКлике, приВводе, число, отклик, обновить } from '../приложение.js';

let сессия = null;        // {дата, начало, упражнения:[{имя, подходы:[...]}]}
let отдыхС = null;        // когда отметили последний подход
let выбранные = null;     // какие упражнения берём в тренировку
let тикает = null;

/** Программа одна — берём первую. Остальные остаются историей для графиков. */
async function программа() {
  const все = await хранилище.всё('программы');
  return все[0] || null;
}

async function историяТренировок() {
  const все = await хранилище.всё('тренировки');
  return все.sort((а, б) => (а.дата < б.дата ? 1 : -1));
}

/** Последний результат: сначала свои тренировки, потом перенесённая история. */
function прошлыйРаз(имя, тренировки, прог) {
  for (const т of тренировки) {
    const у = т.упражнения.find((у) => у.имя === имя);
    const сданные = у?.подходы.filter((п) => п.сдан && п.вес);
    if (сданные?.length) return { дата: т.дата, подходы: сданные };
  }
  const из = прог?.exercises?.find((у) => у.name === имя);
  const последняя = из?.history?.filter((н) => н.weight || (н.sets && н.sets.length)).slice(-1)[0];
  if (!последняя) return null;
  const подходы = последняя.sets
    ? последняя.sets.flatMap((с) => (с.reps || []).map((п) => ({ вес: с.weight, повторы: п })))
    : (последняя.reps || []).map((п) => ({ вес: последняя.weight, повторы: п }));
  return подходы.length ? { неделя: последняя.week, подходы } : null;
}

/** Лучший одноповторный за всю историю — чтобы ловить рекорд. */
function рекорд(имя, тренировки, прог) {
  let лучший = 0;
  const учесть = (вес, повторы, взапасе = 0) => {
    const е = одноповторный(вес, повторы, взапасе);
    if (е && е > лучший) лучший = е;
  };
  for (const т of тренировки) {
    for (const у of т.упражнения.filter((у) => у.имя === имя)) {
      for (const п of у.подходы) if (п.сдан) учесть(п.вес, п.повторы, п.взапасе);
    }
  }
  const из = прог?.exercises?.find((у) => у.name === имя);
  for (const н of из?.history || []) {
    if (н.sets) {
      for (const с of н.sets) for (const п of с.reps || []) учесть(с.weight, п);
    } else {
      for (const п of н.reps || []) учесть(н.weight, п);
    }
  }
  return лучший;
}

function время(мс) {
  const всего = Math.max(0, Math.floor(мс / 1000));
  const мин = String(Math.floor(всего / 60)).padStart(2, '0');
  const сек = String(всего % 60).padStart(2, '0');
  return `${мин}:${сек}`;
}

function запуститьЧасы() {
  clearInterval(тикает);
  тикает = setInterval(() => {
    const общее = document.querySelector('[data-часы]');
    const отдых = document.querySelector('[data-отдых]');
    if (!общее) return clearInterval(тикает);
    if (сессия) общее.textContent = время(Date.now() - сессия.начало);
    if (отдых) {
      отдых.textContent = отдыхС ? 'отдых ' + время(Date.now() - отдыхС) : '';
    }
  }, 1000);
}

export async function показать() {
  const прог = await программа();
  const тренировки = await историяТренировок();

  if (!прог) return нарисовать('<div class="пусто">Программа ещё не загрузилась</div>');

  if (!сессия) {
    if (!выбранные) выбранные = new Set(прог.exercises.map((у) => у.name));

    нарисовать(`
      <h1>Зал</h1>
      <p class="подпись">Отметь, что делаешь сегодня — ${выбранные.size} из ${прог.exercises.length}</p>

      ${прог.exercises.map((у) => {
        const прошлое = прошлыйРаз(у.name, тренировки, прог);
        const лучший = рекорд(у.name, тренировки, прог);
        return `<div class="выборУпр" data-упр="${у.name}"
          ${выбранные.has(у.name) ? 'data-выбрано' : ''}>
          <div class="галка">${выбранные.has(у.name) ? '✓' : ''}</div>
          <div class="тело">
            <div class="имя">${у.name}</div>
            <div class="мелко">${[у.muscles, у.repRange && `${у.repRange} повт.`,
              у.sets && `${у.sets} подх.`].filter(Boolean).join(' · ')}</div>
            <div class="прошлое">${прошлое
              ? 'прошлый раз: ' + прошлое.подходы.map((п) => `${число(п.вес, 1)}×${п.повторы}`).join(' / ')
              : 'записей пока нет'}${лучший ? ` · рекорд ${число(лучший, 1)} кг` : ''}</div>
          </div>
          ${у.видео ? `<button class="кнопка тихая мелкая" data-видео="${у.видео}"
            style="flex:none">Техника</button>` : ''}
        </div>`;
      }).join('')}

      <button class="кнопка" data-начать ${выбранные.size ? '' : 'disabled'}>Начать тренировку</button>

      ${тренировки.length ? `<h2>Последние тренировки</h2>
        ${тренировки.slice(0, 8).map((т) => `<div class="карточка строка">
          <span>${поРусски(т.дата)}</span>
          <span class="мелко">${т.упражнения.length} упр. · ${число(т.тоннаж)} кг${
            т.длительность ? ' · ' + время(т.длительность) : ''}</span>
        </div>`).join('')}` : ''}
    `);
    return привязать();
  }

  // ——— идёт тренировка ———
  нарисовать(`
    <div class="таймер">
      <div>
        <div class="время" data-часы>${время(Date.now() - сессия.начало)}</div>
        <div class="отдых" data-отдых>${отдыхС ? 'отдых ' + время(Date.now() - отдыхС) : ''}</div>
      </div>
      <button class="кнопка тихая мелкая" data-отменить>Отменить</button>
    </div>

    ${сессия.упражнения.map((у, iу) => {
      const прошлое = прошлыйРаз(у.имя, тренировки, прог);
      const лучший = рекорд(у.имя, тренировки, прог);
      const карточка = прог.exercises.find((э) => э.name === у.имя);
      return `<div class="упражнение">
        <div class="строка">
          <div class="имя">${у.имя}</div>
          ${карточка?.видео ? `<button class="кнопка тихая мелкая" data-видео="${карточка.видео}"
            style="white-space:nowrap">Техника</button>` : ''}
        </div>
        <div class="прошлое">${прошлое
          ? 'прошлый раз: ' + прошлое.подходы.map((п) => `${число(п.вес, 1)}×${п.повторы}`).join(' / ')
          : 'первый раз'}</div>
        ${у.подходы.map((п, iп) => {
          const е = одноповторный(п.вес, п.повторы, п.взапасе);
          const новыйРекорд = п.сдан && лучший && е > лучший;
          return `<div class="подход">
            <div class="номер">${iп + 1}</div>
            <input type="number" inputmode="decimal" step="0.5" placeholder="кг"
              data-у="${iу}" data-п="${iп}" data-поле="вес" value="${п.вес ?? ''}">
            <input type="number" inputmode="numeric" step="1" placeholder="повт."
              data-у="${iу}" data-п="${iп}" data-поле="повторы" value="${п.повторы ?? ''}">
            <button class="готово" data-сдать="${iу}:${iп}" ${п.сдан ? 'data-сдан' : ''}>
              ${п.сдан ? '✓' : '○'}</button>
          </div>
          ${новыйРекорд ? '<div class="прошлое рекорд">личный рекорд</div>' : ''}`;
        }).join('')}
        <button class="кнопка тихая" data-подход="${iу}">Ещё подход</button>
      </div>`;
    }).join('')}

    <button class="кнопка" data-завершить>Завершить тренировку</button>
  `);

  запуститьЧасы();
  привязать();
}

function привязать() {
  приКлике('[data-упр]', (карточка, событие) => {
    if (событие.target.closest('[data-видео]')) return;
    const имя = карточка.dataset.упр;
    if (выбранные.has(имя)) выбранные.delete(имя);
    else выбранные.add(имя);
    отклик();
    обновить();
  });

  приКлике('[data-видео]', (кнопка) => {
    отклик();
    const ссылка = кнопка.dataset.видео;
    if (window.Telegram?.WebApp?.openTelegramLink) {
      window.Telegram.WebApp.openTelegramLink(ссылка);
    } else {
      window.open(ссылка, '_blank', 'noopener');
    }
  });

  приКлике('[data-начать]', async () => {
    const прог = await программа();
    сессия = {
      дата: сегодня(),
      начало: Date.now(),
      упражнения: прог.exercises
        .filter((у) => выбранные.has(у.name))
        .map((у) => ({
          имя: у.name,
          подходы: Array.from({ length: Math.max(1, Math.round(у.sets || 2)) },
            () => ({ вес: null, повторы: null, взапасе: null, сдан: false })),
        })),
    };
    отдыхС = null;
    отклик('medium');
    обновить();
  });

  приКлике('[data-подход]', (кнопка) => {
    const у = сессия.упражнения[Number(кнопка.dataset.подход)];
    const последний = у.подходы[у.подходы.length - 1];
    у.подходы.push({ вес: последний?.вес ?? null, повторы: null, взапасе: null, сдан: false });
    отклик();
    обновить();
  });

  приКлике('[data-сдать]', (кнопка) => {
    const [iу, iп] = кнопка.dataset.сдать.split(':').map(Number);
    const подход = сессия.упражнения[iу].подходы[iп];
    подход.сдан = !подход.сдан;
    отдыхС = подход.сдан ? Date.now() : null;
    const следующий = сессия.упражнения[iу].подходы[iп + 1];
    if (подход.сдан && следующий && следующий.вес == null) следующий.вес = подход.вес;
    отклик('medium');
    обновить();
  });

  приВводе('input[data-поле]', (поле) => {
    const { у, п, поле: имя } = поле.dataset;
    const значение = поле.value === '' ? null : Number(поле.value.replace(',', '.'));
    сессия.упражнения[Number(у)].подходы[Number(п)][имя] = Number.isFinite(значение) ? значение : null;
  }, 250);

  приКлике('[data-отменить]', () => {
    сессия = null;
    отдыхС = null;
    clearInterval(тикает);
    обновить();
  });

  приКлике('[data-завершить]', async () => {
    const упражнения = сессия.упражнения
      .map((у) => ({ ...у, подходы: у.подходы.filter((п) => п.сдан && п.вес && п.повторы) }))
      .filter((у) => у.подходы.length);
    const длительность = Date.now() - сессия.начало;

    if (!упражнения.length) {
      сессия = null;
      отдыхС = null;
      clearInterval(тикает);
      return обновить();
    }

    const тоннаж = упражнения.reduce(
      (сумма, у) => сумма + у.подходы.reduce((с, п) => с + п.вес * п.повторы, 0), 0);
    const запись = { ключ: сессия.дата + '-' + Date.now(), дата: сессия.дата,
                     программа: '', упражнения, тоннаж, длительность };
    await хранилище.положить('тренировки', запись.ключ, запись);
    await вОчередь('тренировка', запись);
    await сохранитьДень(сессия.дата, { strength: true });

    сессия = null;
    отдыхС = null;
    clearInterval(тикает);
    отклик('heavy');
    обновить();
  });
}

function заПериод(записи, дней, поле = 'date') {
  const порог = сдвинуть(сегодня(), -дней);
  return записи.filter((з) => новаяДата(з[поле]) > порог);
}

function подписиДат(записи) {
  if (записи.length < 2) return [];
  const коротко = (д) => новаяДата(д).toLocaleDateString('ru-RU', { day: 'numeric', month: 'short' });
  return [коротко(записи[0].date), коротко(записи[Math.floor(записи.length / 2)].date),
          коротко(записи[записи.length - 1].date)];
}

function среднее(записи, поле) {
  const значения = записи.map((з) => з[поле]).filter(Number.isFinite);
  if (!значения.length) return null;
  return значения.reduce((с, з) => с + з, 0) / значения.length;
}

/** Понедельник недели, в которую попадает дата. */
function началоНедели(д) {
  const дата = новаяДата(д);
  const сдвигДней = (дата.getDay() + 6) % 7;
  return сдвинуть(дата, -сдвигДней);
}

/**
 * Насколько закрыт день: три нормы — шаги, калории в пределах планки, белок.
 * Считаются только те, по которым есть записи, поэтому пустой день не «закрыт».
 */
function долиДня(запись, нормы) {
  if (!запись) return { доля: 0, всё: false };
  const части = [];
  if (Number.isFinite(запись.steps)) части.push(Math.min(1, запись.steps / нормы.шаги));
  if (Number.isFinite(запись.kcal)) части.push(запись.kcal <= нормы.ккал ? 1 : нормы.ккал / запись.kcal);
  if (Number.isFinite(запись.protein)) части.push(Math.min(1, запись.protein / нормы.белок));
  if (!части.length) return { доля: 0, всё: false };
  const доля = части.reduce((с, ч) => с + ч, 0) / 3;
  return { доля, всё: части.length === 3 && части.every((ч) => ч >= 0.999) };
}


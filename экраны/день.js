import { день, сохранитьДень, дни, настройки, хранилище } from '../хранилище.js';
import { сегодня, поРусски, сдвинуть, ключДаты, новаяДата, сглаженныйВес, недельныйОтвес,
         калорииИзБЖУ, одноповторный } from '../расчёты.js';
import { линия, столбики, карточка } from '../графики.js';
import { нарисовать, приКлике, приВводе, число, отклик, обновить } from '../приложение.js';

let дата = сегодня();
let периодГрафиков = 90;
let упражнениеГрафика = null;

// Плашки показателей. широкий — на всю ширину, лайм — акцентная.
const ПОКАЗАТЕЛИ = [
  { ключ: 'weight', имя: 'Вес', мера: 'кг', шаг: '0.05', лайм: true },
  { ключ: 'steps', имя: 'Шаги', мера: '', шаг: '100' },
  { ключ: 'kcal', имя: 'Калории', мера: 'ккал', шаг: '1', цель: 'planKcal' },
  { ключ: 'protein', имя: 'Белки', мера: 'г', шаг: '1', цель: 'planProtein' },
  { ключ: 'fat', имя: 'Жиры', мера: 'г', шаг: '1' },
  { ключ: 'carbs', имя: 'Углеводы', мера: 'г', шаг: '1' },
  { ключ: 'fiber', имя: 'Клетчатка', мера: 'г', шаг: '1' },
  { ключ: 'sleep', имя: 'Сон', мера: 'ч', шаг: '0.5' },
  { ключ: 'activityKcal', имя: 'Другая активность', мера: 'ккал', шаг: '10', широкий: true },
];

const ПЕРИОДЫ = [
  { дней: 30, имя: '30 дней' },
  { дней: 90, имя: '3 месяца' },
  { дней: 365, имя: 'год' },
  { дней: 3650, имя: 'всё' },
];

function заПериод(записи, дней, поле = 'date') {
  const порог = сдвинуть(сегодня(), -дней);
  return записи.filter((з) => новаяДата(з[поле]) > порог);
}

function подписиДат(записи) {
  if (записи.length < 2) return [];
  const коротко = (д) => новаяДата(д).toLocaleDateString('ru-RU', { day: 'numeric', month: 'short' });
  return [коротко(записи[0].date), коротко(записи[Math.floor(записи.length / 2)].date),
          коротко(записи[записи.length - 1].date)];
}

function среднее(записи, поле) {
  const значения = записи.map((з) => з[поле]).filter(Number.isFinite);
  if (!значения.length) return null;
  return значения.reduce((с, з) => с + з, 0) / значения.length;
}

export async function показать() {
  const запись = await день(дата);
  const н = await настройки();
  const все = await дни();
  const тренировки = (await хранилище.всё('тренировки')).sort((а, б) => (а.дата < б.дата ? -1 : 1));
  const программы = await хранилище.всё('программы');

  const ряд = сглаженныйВес(все.map((д) => ({ date: д.date, вес: д.weight })));
  const последний = ряд[ряд.length - 1];
  const отвес = недельныйОтвес(все.map((д) => ({ date: д.date, вес: д.weight })));

  const планКкал = н.planKcal || 1600;
  const планБелок = н.planProtein || 140;

  // неделя, в которую попадает выбранный день
  const неделя = все.filter((д) => {
    const разница = (новаяДата(дата) - новаяДата(д.date)) / 86400000;
    return разница >= 0 && разница < 7;
  });
  const силовыхЗаНеделю = неделя.filter((д) => д.strength).length;

  const окно = заПериод(все, периодГрафиков);
  const рядОкна = сглаженныйВес(окно.map((д) => ({ date: д.date, вес: д.weight })));
  const скалориями = окно.filter((д) => Number.isFinite(д.kcal));
  const сбелком = окно.filter((д) => Number.isFinite(д.protein));
  const сошагами = окно.filter((д) => Number.isFinite(д.steps));
  const сосном = окно.filter((д) => Number.isFinite(д.sleep));
  const сактивностью = окно.filter((д) => Number.isFinite(д.activityKcal));

  const имена = new Set();
  for (const п of программы) for (const у of п.exercises || []) имена.add(у.name);
  for (const т of тренировки) for (const у of т.упражнения) имена.add(у.имя);
  const списокУпражнений = [...имена];
  const выбранное = упражнениеГрафика && имена.has(упражнениеГрафика)
    ? упражнениеГрафика : списокУпражнений[0];

  нарисовать(`
    <div class="даты">
      <button class="стрелка" data-сдвиг="-1">‹</button>
      <div class="середина">
        <b>${дата === сегодня() ? 'Сегодня' : поРусски(дата)}</b>
        <input type="date" data-выбор-даты value="${дата}" max="${сегодня()}">
      </div>
      <button class="стрелка" data-сдвиг="1" ${дата >= сегодня() ? 'disabled' : ''}>›</button>
    </div>

    <div class="показатели">
      ${ПОКАЗАТЕЛИ.map((п) => {
        const значение = запись[п.ключ];
        const цель = п.цель === 'planKcal' ? планКкал : п.цель === 'planProtein' ? планБелок : null;
        return `<div class="показатель ${п.лайм ? 'лайм' : ''} ${п.широкий ? 'широкий' : ''}">
          <div class="имя">${п.имя}</div>
          <div>
            <div class="низ">
              <input type="number" inputmode="decimal" step="${п.шаг}" data-поле="${п.ключ}"
                value="${Number.isFinite(значение) ? значение : ''}" placeholder="—">
              ${п.мера ? `<span class="мера">${п.мера}</span>` : ''}
            </div>
            ${цель ? `<div class="цель">из ${число(цель)}${
              Number.isFinite(значение) ? ` · осталось ${число(цель - значение)}` : ''}</div>` : ''}
            ${п.ключ === 'weight' && последний
              ? `<div class="цель">с поправкой ${число(последний.сглаженный, 1)} кг</div>` : ''}
          </div>
        </div>`;
      }).join('')}

      <div class="показатель широкий">
        <div class="имя">Силовая тренировка</div>
        <div class="выбор">
          <button data-силовая="да" ${запись.strength ? 'data-активно' : ''}>была</button>
          <button data-силовая="нет" ${запись.strength ? '' : 'data-активно'}>не было</button>
        </div>
      </div>

      <div class="показатель широкий">
        <div class="имя">Сытость</div>
        <div class="выбор">
          ${[1, 2, 3, 4, 5].map((б) => `<button data-сытость="${б}"
            ${запись.satiety === б ? 'data-активно' : ''}>${б}</button>`).join('')}
        </div>
      </div>
    </div>

    <h2>За неделю</h2>
    <div class="сводка">
      <div><div class="значение">${число(среднее(неделя, 'kcal'))}</div><div class="имя">ккал</div></div>
      <div><div class="значение">${число(среднее(неделя, 'protein'))}</div><div class="имя">белок</div></div>
      <div><div class="значение">${число(среднее(неделя, 'steps'))}</div><div class="имя">шаги</div></div>
      <div><div class="значение">${число(среднее(неделя, 'sleep'), 1)}</div><div class="имя">сон</div></div>
      <div><div class="значение">${число(среднее(неделя, 'weight'), 1)}</div><div class="имя">вес</div></div>
      <div><div class="значение">${силовыхЗаНеделю}</div><div class="имя">силовых</div></div>
    </div>

    <h2>Графики</h2>
    <div class="пилюли">
      ${ПЕРИОДЫ.map((п) => `<button data-период="${п.дней}"
        ${периодГрафиков === п.дней ? 'data-активно' : ''}>${п.имя}</button>`).join('')}
    </div>

    ${карточка('Вес',
      рядОкна.length
        ? число(рядОкна[рядОкна.length - 1].сглаженный, 1) + ' кг'
          + (отвес.статус === 'ок'
            ? ` · ${отвес.процент > 0 ? '+' : ''}${число(отвес.процент, 2)}% за неделю` : '')
        : '',
      линия([
        { значения: рядОкна.map((т) => т.вес), цвет: 'var(--текст2)', толщина: 1.2, прозрачность: 0.5 },
        { значения: рядОкна.map((т) => т.сглаженный), цвет: 'var(--лайм)', толщина: 2.4 },
      ], подписиДат(рядОкна)))}

    ${карточка('Калории',
      скалориями.length ? 'в среднем ' + число(среднее(скалориями, 'kcal')) : '',
      столбики(скалориями.map((д) => д.kcal), { цель: планКкал, подписи: подписиДат(скалориями) }))}

    ${карточка('Белок',
      сбелком.length ? 'в среднем ' + число(среднее(сбелком, 'protein')) + ' г' : '',
      столбики(сбелком.map((д) => д.protein), { подписи: подписиДат(сбелком), цвет: 'var(--белый)' }))}

    ${карточка('Шаги',
      сошагами.length ? 'в среднем ' + число(среднее(сошагами, 'steps')) : '',
      столбики(сошагами.map((д) => д.steps), { подписи: подписиДат(сошагами) }))}

    ${сактивностью.length ? карточка('Другая активность',
      'в среднем ' + число(среднее(сактивностью, 'activityKcal')) + ' ккал',
      столбики(сактивностью.map((д) => д.activityKcal), { подписи: подписиДат(сактивностью),
        цвет: 'var(--белый)' })) : ''}

    ${карточка('Сон',
      сосном.length ? 'в среднем ' + число(среднее(сосном, 'sleep'), 1) + ' ч' : '',
      столбики(сосном.map((д) => д.sleep), { подписи: подписиДат(сосном), цвет: 'var(--белый)' }))}

    ${тренировки.length ? карточка('Тоннаж тренировок',
      число(тренировки[тренировки.length - 1].тоннаж) + ' кг в последней',
      столбики(заПериод(тренировки, периодГрафиков, 'дата').map((т) => т.тоннаж), {})) : ''}

    ${списокУпражнений.length ? `<h2>Прогресс по упражнению</h2>
      <div class="карточка" style="padding:12px 14px">
        <select data-упражнение>
          ${списокУпражнений.map((и) => `<option ${и === выбранное ? 'selected' : ''}>${и}</option>`).join('')}
        </select>
      </div>
      ${графикУпражнения(выбранное, тренировки, программы)}` : ''}
  `);

  приВводе('input[data-поле]', async (поле) => {
    const значение = поле.value === '' ? null : Number(поле.value.replace(',', '.'));
    await сохранитьДень(дата, { [поле.dataset.поле]: Number.isFinite(значение) ? значение : null });
  });

  приКлике('[data-сдвиг]', (кнопка) => {
    дата = ключДаты(сдвинуть(дата, Number(кнопка.dataset.сдвиг)));
    отклик();
    обновить();
  });

  приКлике('[data-силовая]', async (кнопка) => {
    await сохранитьДень(дата, { strength: кнопка.dataset.силовая === 'да' });
    отклик('medium');
    обновить();
  });

  приКлике('[data-сытость]', async (кнопка) => {
    const было = (await день(дата)).satiety;
    const стало = Number(кнопка.dataset.сытость);
    await сохранитьДень(дата, { satiety: было === стало ? null : стало });
    отклик();
    обновить();
  });

  приКлике('[data-период]', (кнопка) => {
    периодГрафиков = Number(кнопка.dataset.период);
    отклик();
    обновить();
  });

  document.querySelector('[data-выбор-даты]')?.addEventListener('change', (е) => {
    if (!е.target.value) return;
    дата = е.target.value;
    обновить();
  });

  document.querySelector('[data-упражнение]')?.addEventListener('change', (е) => {
    упражнениеГрафика = е.target.value;
    обновить();
  });
}

function графикУпражнения(имя, тренировки, программы) {
  if (!имя) return '';
  const точки = [];

  for (const п of программы) {
    const у = (п.exercises || []).find((у) => у.name === имя);
    for (const н of у?.history || []) {
      const подходы = н.sets
        ? н.sets.flatMap((с) => (с.reps || []).map((п) => ({ вес: с.weight, повторы: п })))
        : (н.reps || []).map((п) => ({ вес: н.weight, повторы: п }));
      const лучший = подходы.reduce((м, п) => Math.max(м, одноповторный(п.вес, п.повторы) || 0), 0);
      if (лучший) точки.push({ метка: 'н' + н.week, сила: лучший });
    }
  }
  for (const т of тренировки) {
    for (const у of т.упражнения.filter((у) => у.имя === имя)) {
      const лучший = у.подходы.reduce(
        (м, п) => Math.max(м, одноповторный(п.вес, п.повторы, п.взапасе) || 0), 0);
      if (лучший) точки.push({ метка: т.дата.slice(5), сила: лучший });
    }
  }

  if (точки.length < 2) return '<div class="пусто">Нужно хотя бы две записи</div>';
  const рост = ((точки[точки.length - 1].сила - точки[0].сила) / точки[0].сила) * 100;
  return карточка(имя,
    `${число(точки[точки.length - 1].сила, 1)} кг · ${рост > 0 ? '+' : ''}${число(рост, 1)}%`,
    линия([{ значения: точки.map((т) => т.сила), цвет: 'var(--лайм)', толщина: 2.4 }],
      [точки[0].метка, точки[Math.floor(точки.length / 2)].метка, точки[точки.length - 1].метка]));
}
